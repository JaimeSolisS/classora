"""Families factories (#33 H6, #34 H6, #172 G4): student profiles with
emergency contacts, guardian profiles, student-guardian links, and family
groupings with their members.

For #35, M6 (billing accounts on ``families``) and later milestones. All
data is synthetic (``es_MX`` Faker names, reserved-domain emails). Phone
numbers are not generated by Faker: they come from a sequence under the
``+52 00`` prefix, and Mexican area codes never start with ``0``, so no
generated number can be a real one.

The default birthdate (2012-2016, a fixed range) makes the student a minor
until 2030; pass ``birthdate=`` for an adult.
"""

from datetime import date
from typing import Any

import factory
from sqlalchemy.ext.asyncio import AsyncSession

from app.modules.families.models import (
    Family,
    FamilyGuardian,
    FamilyStudent,
    Guardian,
    Student,
    StudentEmergencyContact,
    StudentGuardian,
)
from tests.factories.base import ClassoraFactory, calendar_date, get_faker, persist


def fictitious_phone(n: int) -> str:
    """A phone number no real line has (area code ``00``)."""
    return f"+52 00 {n // 10000 % 10000:04d} {n % 10000:04d}"


class StudentFactory(ClassoraFactory):
    """An active student profile without a level (a minor by default)."""

    class Meta:
        model = Student

    given_names = factory.Faker("first_name")
    family_names = factory.LazyFunction(
        lambda: f"{get_faker().last_name()} {get_faker().last_name()}"
    )
    birthdate = calendar_date(date(2012, 1, 1), date(2016, 12, 31))
    email = None
    phone = None
    school_name = None
    school_grade = None
    education_level_id = None
    is_active = True


class StudentEmergencyContactFactory(ClassoraFactory):
    """A contact; pass ``student_id`` and ``position``."""

    class Meta:
        model = StudentEmergencyContact

    name = factory.Faker("name")
    relationship = factory.Iterator(["Madre", "Padre", "Abuela", "Tío", "Vecina"])
    phone = factory.Sequence(lambda n: fictitious_phone(n + 1))
    position = 1


async def persist_student(
    session: AsyncSession, *, contacts: int = 1, **overrides: Any
) -> Student:
    """Persist a :class:`StudentFactory` student with ``contacts`` (1-5)
    emergency contacts at positions 1..n. Flushes, never commits."""
    student: Student = await persist(session, StudentFactory, **overrides)
    for position in range(1, contacts + 1):
        await persist(
            session,
            StudentEmergencyContactFactory,
            student_id=student.id,
            position=position,
        )
    return student


class GuardianFactory(ClassoraFactory):
    """An active guardian profile without an account or contact data (pass
    ``user_id`` to link an account holding the ``guardian`` role)."""

    class Meta:
        model = Guardian

    given_names = factory.Faker("first_name")
    family_names = factory.LazyFunction(
        lambda: f"{get_faker().last_name()} {get_faker().last_name()}"
    )
    email = None
    phone = None
    user_id = None
    is_active = True


async def link_guardian(
    session: AsyncSession,
    student: Student,
    guardian: Guardian,
    relationship: str = "mother",
) -> StudentGuardian:
    """Persist a link between ``student`` and ``guardian`` (a code of
    ``GUARDIAN_RELATIONSHIPS``). Flushes, never commits."""
    link = StudentGuardian(
        student_id=student.id, guardian_id=guardian.id, relationship=relationship
    )
    session.add(link)
    await session.flush()
    return link


class FamilyFactory(ClassoraFactory):
    """An active family with no members (``Familia <two last names>``)."""

    class Meta:
        model = Family

    name = factory.LazyFunction(
        lambda: f"Familia {get_faker().last_name()} {get_faker().last_name()}"
    )
    is_active = True


async def add_to_family(
    session: AsyncSession,
    family: Family,
    *members: Student | Guardian,
) -> list[FamilyStudent | FamilyGuardian]:
    """Persist ``family`` membership rows for students and guardian profiles
    (each may belong to one family only). Flushes, never commits."""
    rows: list[FamilyStudent | FamilyGuardian] = []
    for member in members:
        if isinstance(member, Student):
            rows.append(FamilyStudent(family_id=family.id, student_id=member.id))
        else:
            rows.append(FamilyGuardian(family_id=family.id, guardian_id=member.id))
    session.add_all(rows)
    await session.flush()
    return rows
